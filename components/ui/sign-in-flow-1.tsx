export const SignInPage = ({ className }: SignInPageProps) => {
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [errorMsg, setErrorMsg] = useState("");
  const [step, setStep] = useState<"email" | "code" | "success">("email");
  const [code, setCode] = useState(["", "", "", "", "", ""]);
  const codeInputRefs = useRef<(HTMLInputElement | null)[]>([]);
  const [generatedOtp, setGeneratedOtp] = useState("");
  const [otpError, setOtpError] = useState("");

  const [initialCanvasVisible, setInitialCanvasVisible] = useState(true);
  const [reverseCanvasVisible, setReverseCanvasVisible] = useState(false);
  const [showGoogleMock, setShowGoogleMock] = useState(false);

  const router = useRouter();

  const handleGoogleAuth = () => {
    setShowGoogleMock(true);
  };

  const handleSelectAccount = (selectedEmail: string) => {
    setShowGoogleMock(false);
    
    // Save to users list if not already registered
    const users = JSON.parse(localStorage.getItem("users") || "[]");
    if (!users.find((u: any) => u.email === selectedEmail)) {
      users.push({ email: selectedEmail, password: "google-auth" });
      localStorage.setItem("users", JSON.stringify(users));
    }

    localStorage.setItem("token", "demo-google-token-" + Date.now());
    localStorage.setItem("user", JSON.stringify({ email: selectedEmail, role: "USER" }));
    router.push("/dashboard");
  };

  const handleLogin = async () => {
    setErrorMsg("");
    if (!email || !password) {
      setErrorMsg("Please enter email and password");
      return;
    }

    const users = JSON.parse(localStorage.getItem("users") || "[]");
    const user = users.find((u: any) => u.email === email);

    if (!user) {
      setErrorMsg("Account not found. Redirecting to register...");
      setTimeout(() => router.push("/register"), 2000);
      return;
    }

    if (user.password !== password) {
      setErrorMsg("Incorrect password. Please try again.");
      return;
    }

    // Set auth info
    localStorage.setItem("token", "demo-token-" + Date.now());
    localStorage.setItem("user", JSON.stringify({ email: user.email, role: "USER" }));

    // Show reverse canvas
    setReverseCanvasVisible(true);
    
    // Hide original canvas
    setTimeout(() => {
      setInitialCanvasVisible(false);
    }, 50);
    
    // Transition to success screen after animation
    setTimeout(() => {
      setStep("success");
    }, 2000);
  };

  const handleEmailSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (email) {
      setStep("code");
    }
  };

  // Focus first input when code screen appears
  useEffect(() => {
    if (step === "code") {
      setTimeout(() => {
        codeInputRefs.current[0]?.focus();
      }, 500);
    }
  }, [step]);

  const handleCodeChange = (index: number, value: string) => {
    if (value.length <= 1) {
      const newCode = [...code];
      newCode[index] = value;
      setCode(newCode);
      
      // Focus next input if value is entered
      if (value && index < 5) {
        codeInputRefs.current[index + 1]?.focus();
      }
      
      // Check if code is complete
      if (index === 5 && value) {
        const isComplete = newCode.every(digit => digit.length === 1);
        if (isComplete) {
          const enteredCode = newCode.join("");
          if (enteredCode !== generatedOtp) {
            setCode(["", "", "", "", "", ""]);
            codeInputRefs.current[0]?.focus();
            setOtpError("Invalid verification code. Please try again.");
            return;
          }
          setOtpError("");

          // First show the new reverse canvas
          setReverseCanvasVisible(true);
          
          // Then hide the original canvas after a small delay
          setTimeout(() => {
            setInitialCanvasVisible(false);
          }, 50);
          
          // Transition to success screen after animation
          setTimeout(() => {
            setStep("success");
          }, 2000);
        }
      }
    }
  };

  const handleKeyDown = (index: number, e: React.KeyboardEvent<HTMLInputElement>) => {
    if (e.key === "Backspace" && !code[index] && index > 0) {
      codeInputRefs.current[index - 1]?.focus();
    }
  };

  const handleBackClick = () => {
    setStep("email");
    setCode(["", "", "", "", "", ""]);
    // Reset animations if going back
    setReverseCanvasVisible(false);
    setInitialCanvasVisible(true);
  };

  return (
    <div className={cn("flex w-[100%] flex-col min-h-screen bg-black dark:bg-black light:bg-white relative transition-colors duration-300", className)}>
      <SpringDotsCanvas />
      <div className="absolute inset-0 z-0 opacity-40">

        {/* Initial canvas (forward animation) */}
        {initialCanvasVisible && (
          <div className="absolute inset-0">
            <CanvasRevealEffect
              animationSpeed={3}
              containerClassName="bg-black"
              colors={[
                [255, 255, 255],
                [255, 255, 255],
              ]}
              dotSize={6}
              reverse={false}
            />
          </div>
        )}
        
        {/* Reverse canvas (appears when code is complete) */}
        {reverseCanvasVisible && (
          <div className="absolute inset-0">
            <CanvasRevealEffect
              animationSpeed={4}
              containerClassName="bg-black"
              colors={[
                [255, 255, 255],
                [255, 255, 255],
              ]}
              dotSize={6}
              reverse={true}
            />
          </div>
        )}
        
        <div className="absolute inset-0 bg-[radial-gradient(circle_at_center,_rgba(0,0,0,1)_0%,_transparent_100%)]" />
        <div className="absolute top-0 left-0 right-0 h-1/3 bg-gradient-to-b from-black to-transparent" />
      </div>
      
      <GoogleMockModal 
        isOpen={showGoogleMock} 
        onClose={() => setShowGoogleMock(false)} 
        onSelectAccount={handleSelectAccount} 
      />

      {/* Content Layer */}
      <div className="relative z-10 flex flex-col flex-1">
        {/* Top navigation */}
        <MiniNavbar />

        {/* Main content container */}
        <div className="flex flex-1 flex-col lg:flex-row ">
          {/* Left side (form) */}
          <div className="flex-1 flex flex-col justify-center items-center">
            <div className="w-full mt-[80px] max-w-sm">
              <AnimatePresence mode="wait">
                {step === "email" ? (
                  <motion.div 
                    key="email-step"
                    initial={{ opacity: 0, x: -100 }}
                    animate={{ opacity: 1, x: 0 }}
                    exit={{ opacity: 0, x: -100 }}
                    transition={{ duration: 0.4, ease: "easeOut" }}
                    className="space-y-3 text-center"
                  >
                    <div className="space-y-1">
                      <h1 className="text-[3rem] sm:text-[3.5rem] font-extrabold leading-[1.1] tracking-tight text-white mb-2">Welcome to TeamMerge Pro</h1>
                    </div>


                    <div className="space-y-2">
                      
                      <div className="flex items-center gap-4">
                        <div className="h-px bg-white/10 flex-1" />
                        <span className="text-white/40 text-sm">credentials</span>
                        <div className="h-px bg-white/10 flex-1" />
                      </div>
                      
                      <div>
                        <input 
                          type="email" 
                          placeholder="Email"
                          value={email}
                          onChange={(e) => setEmail(e.target.value)}
                          className="w-full bg-white/5 text-white placeholder:text-white/40 border border-white/20 rounded-full py-3 px-4 focus:outline-none focus:border-white/50 focus:bg-white/10 text-center transition-all"
                          required
                        />
                        <input 
                          type="password" 
                          placeholder="Password"
                          value={password}
                          onChange={(e) => {
                            setPassword(e.target.value);
                            setErrorMsg("");
                          }}
                          className={`w-full bg-white/5 text-white placeholder:text-white/40 border border-white/20 rounded-full py-3 px-4 focus:outline-none focus:border-white/50 focus:bg-white/10 text-center mt-3 transition-all ${
                            errorMsg ? "border-red-500/80" : ""
                          }`}
                          required
                        />
                        {errorMsg && (
                          <p className="text-red-400 text-xs mt-2 text-center">{errorMsg}</p>
                        )}
                        {/* Remember Me */}
                        <div className="flex items-center justify-between mt-3 px-1">
                          <label className="flex items-center gap-2 cursor-pointer select-none">
                            <input
                              type="checkbox"
                              className="w-4 h-4 rounded border border-white/20 bg-transparent accent-white cursor-pointer"
                            />
                            <span className="text-sm text-white/50">Remember me</span>
                          </label>
                        </div>

                        <button 
                          type="button"
                          onClick={handleLogin}
                          className="w-full rounded-full bg-white text-black font-medium py-3 hover:bg-white/90 transition-colors mt-4"
                        >
                          Login
                        </button>

                        {/* Divider */}
                        <div className="flex items-center gap-4 mt-4">
                          <div className="h-px bg-white/10 flex-1" />
                          <span className="text-white/40 text-sm">or</span>
                          <div className="h-px bg-white/10 flex-1" />
                        </div>

                        {/* Google Login */}
                        <button
                          type="button"
                          onClick={handleGoogleAuth}
                          className="w-full rounded-full border border-white/10 bg-transparent text-white font-medium py-3 hover:border-white/30 hover:bg-white/5 transition-colors mt-3 flex items-center justify-center gap-3"
                        >
                          <svg className="w-5 h-5" viewBox="0 0 24 24" xmlns="http://www.w3.org/2000/svg">
                            <path d="M22.56 12.25c0-.78-.07-1.53-.2-2.25H12v4.26h5.92a5.06 5.06 0 01-2.2 3.32v2.77h3.57c2.08-1.92 3.28-4.74 3.28-8.1z" fill="#4285F4"/>
                            <path d="M12 23c2.97 0 5.46-.98 7.28-2.66l-3.57-2.77c-.98.66-2.23 1.06-3.71 1.06-2.86 0-5.29-1.93-6.16-4.53H2.18v2.84C3.99 20.53 7.7 23 12 23z" fill="#34A853"/>
                            <path d="M5.84 14.09c-.22-.66-.35-1.36-.35-2.09s.13-1.43.35-2.09V7.07H2.18C1.43 8.55 1 10.22 1 12s.43 3.45 1.18 4.93l2.85-2.22.81-.62z" fill="#FBBC05"/>
                            <path d="M12 5.38c1.62 0 3.06.56 4.21 1.64l3.15-3.15C17.45 2.09 14.97 1 12 1 7.7 1 3.99 3.47 2.18 7.07l3.66 2.84c.87-2.6 3.3-4.53 6.16-4.53z" fill="#EA4335"/>
                          </svg>
                          Continue with Google
                        </button>

                        <div className="text-center mt-3">
                          <a href="/forgot-password" className="text-white/50 hover:text-white/70 text-sm transition-colors">
                            Forgot Password?
                          </a>
                        </div>
                        <div className="text-center mt-3 text-sm text-white/40">
                          Don&apos;t have an account?{" "}
                          <a href="/register" className="text-white/70 hover:text-white transition-colors underline">
                            Register
                          </a>
                        </div>
                      </div>
                    </div>
                    
                    <p className="text-xs text-white/40 pt-4">
                      By signing up, you agree to the <Link href="#" className="underline text-white/40 hover:text-white/60 transition-colors">MSA</Link>, <Link href="#" className="underline text-white/40 hover:text-white/60 transition-colors">Product Terms</Link>, <Link href="#" className="underline text-white/40 hover:text-white/60 transition-colors">Policies</Link>, <Link href="#" className="underline text-white/40 hover:text-white/60 transition-colors">Privacy Notice</Link>, and <Link href="#" className="underline text-white/40 hover:text-white/60 transition-colors">Cookie Notice</Link>.
                    </p>
                  </motion.div>
                ) : step === "code" ? (
                  <motion.div 
                    key="code-step"
                    initial={{ opacity: 0, x: 100 }}
                    animate={{ opacity: 1, x: 0 }}
                    exit={{ opacity: 0, x: 100 }}
                    transition={{ duration: 0.4, ease: "easeOut" }}
                    className="space-y-6 text-center"
                  >
                    <div className="space-y-1">
                      <h1 className="text-[2.5rem] font-bold leading-[1.1] tracking-tight text-white">We sent you a code</h1>
                      <p className="text-[1.25rem] text-white/50 font-light">Please enter it</p>
                    </div>
                    
                    <div className="w-full">
                      <div className={`relative rounded-full py-4 px-5 border bg-transparent ${otpError ? 'border-red-500' : 'border-white/10'}`}>
                        <div className="flex items-center justify-center">
                          {code.map((digit, i) => (
                            <div key={i} className="flex items-center">
                              <div className="relative">
                                <input
                                  ref={(el) => {
                                    codeInputRefs.current[i] = el;
                                  }}
                                  type="text"
                                  inputMode="numeric"
                                  pattern="[0-9]*"
                                  maxLength={1}
                                  value={digit}
                                  onChange={e => handleCodeChange(i, e.target.value)}
                                  onKeyDown={e => handleKeyDown(i, e)}
                                  className="w-8 text-center text-xl bg-transparent text-white border-none focus:outline-none focus:ring-0 appearance-none"
                                  style={{ caretColor: 'transparent' }}
                                />
                                {!digit && (
                                  <div className="absolute top-0 left-0 w-full h-full flex items-center justify-center pointer-events-none">
                                    <span className="text-xl text-white">0</span>
                                  </div>
                                )}
                              </div>
                              {i < 5 && <span className="text-white/20 text-xl">|</span>}
                            </div>
                          ))}
                        </div>
                      </div>
                      {otpError && <p className="text-red-400 text-xs mt-3 text-center">{otpError}</p>}
                    </div>
                    
                    <div>
                      <motion.button 
                        onClick={() => {
                          const otpCode = Math.floor(100000 + Math.random() * 900000).toString();
                          setGeneratedOtp(otpCode);
                          setCode(["", "", "", "", "", ""]);
                          setOtpError("");
                          codeInputRefs.current[0]?.focus();
                          
                          // Call actual email API
                          try {
                            fetch("/api/send-otp", {
                              method: "POST",
                              headers: { "Content-Type": "application/json" },
                              body: JSON.stringify({ email, otp: otpCode }),
                            });
                          } catch (e) {
                            console.error("Email failed to send", e);
                          }
                        }}
                        className="text-white/50 hover:text-white/70 transition-colors cursor-pointer text-sm bg-transparent border-none"
                        whileHover={{ scale: 1.02 }}
                        transition={{ duration: 0.2 }}
                      >
                        Resend code
                      </motion.button>
                    </div>
                    
                    <div className="flex w-full gap-3">
                      <motion.button 
                        onClick={handleBackClick}
                        className="rounded-full bg-white text-black font-medium px-8 py-3 hover:bg-white/90 transition-colors w-[30%]"
                        whileHover={{ scale: 1.02 }}
                        whileTap={{ scale: 0.98 }}
                        transition={{ duration: 0.2 }}
                      >
                        Back
                      </motion.button>
                      <motion.button 
                        className={`flex-1 rounded-full font-medium py-3 border transition-all duration-300 ${
                          code.every(d => d !== "") 
                          ? "bg-white text-black border-transparent hover:bg-white/90 cursor-pointer" 
                          : "bg-[#111] text-white/50 border-white/10 cursor-not-allowed"
                        }`}
                        disabled={!code.every(d => d !== "")}
                      >
                        Continue
                      </motion.button>
                    </div>
                    
                    <div className="pt-16">
                      <p className="text-xs text-white/40">
                        By signing up, you agree to the <Link href="#" className="underline text-white/40 hover:text-white/60 transition-colors">MSA</Link>, <Link href="#" className="underline text-white/40 hover:text-white/60 transition-colors">Product Terms</Link>, <Link href="#" className="underline text-white/40 hover:text-white/60 transition-colors">Policies</Link>, <Link href="#" className="underline text-white/40 hover:text-white/60 transition-colors">Privacy Notice</Link>, and <Link href="#" className="underline text-white/40 hover:text-white/60 transition-colors">Cookie Notice</Link>.
                      </p>
                    </div>
                  </motion.div>
                ) : (
                  <motion.div 
                    key="success-step"
                    initial={{ opacity: 0, y: 50 }}
                    animate={{ opacity: 1, y: 0 }}
                    transition={{ duration: 0.4, ease: "easeOut", delay: 0.3 }}
                    className="space-y-6 text-center"
                  >
                    <div className="space-y-1">
                      <h1 className="text-[2.5rem] font-bold leading-[1.1] tracking-tight text-white">You're in!</h1>
                      <p className="text-[1.25rem] text-white/50 font-light">Welcome</p>
                    </div>
                    
                    <motion.div 
                      initial={{ scale: 0.8, opacity: 0 }}
                      animate={{ scale: 1, opacity: 1 }}
                      transition={{ duration: 0.5, delay: 0.5 }}
                      className="py-10"
                    >
                      <div className="mx-auto w-16 h-16 rounded-full bg-gradient-to-br from-white to-white/70 flex items-center justify-center">
                        <svg xmlns="http://www.w3.org/2000/svg" className="h-8 w-8 text-black" viewBox="0 0 20 20" fill="currentColor">
                          <path fillRule="evenodd" d="M16.707 5.293a1 1 0 010 1.414l-8 8a1 1 0 01-1.414 0l-4-4a1 1 0 011.414-1.414L8 12.586l7.293-7.293a1 1 0 011.414 0z" clipRule="evenodd" />
                        </svg>
                      </div>
                    </motion.div>
                    
                    <motion.button 
                      initial={{ opacity: 0 }}
                      animate={{ opacity: 1 }}
                      transition={{ delay: 1 }}
                      onClick={() => router.push("/dashboard")}
                      className="w-full rounded-full bg-white text-black font-medium py-3 hover:bg-white/90 transition-colors"
                    >
                      Continue to Dashboard
                    </motion.button>
                  </motion.div>
                )}
              </AnimatePresence>
            </div>
          </div>
          
        </div>
      </div>
    </div>
  );
};
